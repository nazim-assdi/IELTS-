/**
 * Filter vocabulary by various user criteria
 */
export function filterVocabulary(
  items: VocabularyItem[],
  options: VocabularyFilterOptions
): VocabularyItem[] {
  const {
    searchQuery = '',
    sectionNumber = 'all',
    minBand = 'all',
    vocabType = 'all',
    bookmarkedOnly = false,
    bookmarkedIds = [],
  } = options;

  const cleanQuery = searchQuery.trim().toLowerCase();
  const bookmarkedSet = new Set(bookmarkedIds);

  return items.filter((item) => {
    // 1. Bookmark filter
    if (bookmarkedOnly && !bookmarkedSet.has(item.id)) {
      return false;
    }

    // 2. Section filter
    if (sectionNumber !== 'all' && item.sectionNumber !== sectionNumber) {
      return false;
    }

    // 3. Band filter
    if (minBand !== 'all' && item.bandLevel < minBand) {
      return false;
    }

    // 4. Vocab type filter
    if (vocabType !== 'all' && item.type !== vocabType) {
      return false;
    }

    // 5. Search query
    if (cleanQuery) {
      const matchTerm = item.term.toLowerCase().includes(cleanQuery);
      const matchDef = item.definition.toLowerCase().includes(cleanQuery);
      const matchEx = item.exampleSentence.toLowerCase().includes(cleanQuery);
      const matchUnit = item.unitTitle.toLowerCase().includes(cleanQuery);
      const matchSynonyms = item.synonymsOrAlternatives?.some(s => s.toLowerCase().includes(cleanQuery));

      if (!matchTerm && !matchDef && !matchEx && !matchUnit && !matchSynonyms) {
        return false;
      }
    }

    return true;
  });
}

/**
 * Toggle bookmark for a term ID
 */
export function toggleBookmark(currentBookmarkedIds: string[], termId: string): string[] {
  if (!termId) return [...currentBookmarkedIds];
  const set = new Set(currentBookmarkedIds);
  if (set.has(termId)) {
    set.delete(termId);
  } else {
    set.add(termId);
  }
  return Array.from(set);
}

/**
 * Calculate vocabulary statistics
 */
export function getVocabularyStats(
  items: VocabularyItem[],
  bookmarkedIds: string[]
): VocabularyStats {
  const bookmarkedSet = new Set(bookmarkedIds);
  let bookmarkedCount = 0;

  const bandCounts = {
    band7: 0,
    band8: 0,
    band85: 0,
    band9: 0,
  };

  const typeCounts: Record<VocabularyType, number> = {
    'collocation': 0,
    'idiom': 0,
    'phrasal-verb': 0,
    'academic-lexis': 0,
    'discourse-marker': 0,
  };

  const sectionCounts: Record<number, number> = {};

  for (const item of items) {
    if (bookmarkedSet.has(item.id)) {
      bookmarkedCount++;
    }

    // Band counts
    if (item.bandLevel >= 9.0) {
      bandCounts.band9++;
    } else if (item.bandLevel >= 8.5) {
      bandCounts.band85++;
    } else if (item.bandLevel >= 8.0) {
      bandCounts.band8++;
    } else {
      bandCounts.band7++;
    }

    // Type counts
    if (typeCounts[item.type] !== undefined) {
      typeCounts[item.type]++;
    }

    // Section counts
    sectionCounts[item.sectionNumber] = (sectionCounts[item.sectionNumber] || 0) + 1;
  }

  return {
    totalTerms: items.length,
    bookmarkedCount,
    bandCounts,
    typeCounts,
    sectionCounts,
  };
}

/**
 * Safe local storage load/save helpers
 */
export function loadBookmarkedVocab(): string[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(VOCABULARY_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveBookmarkedVocab(ids: string[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(VOCABULARY_STORAGE_KEY, JSON.stringify(ids));
  } catch {}
}
